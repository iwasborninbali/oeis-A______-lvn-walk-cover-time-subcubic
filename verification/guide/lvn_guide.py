#!/usr/bin/env python3
"""Guide's independent check of the least-visited-neighbour walk maxima (written from the definition, 13 Nov 2026).

Graphs: all connected simple graphs with maximum degree <= 3 on n vertices, generated by adding one vertex (joined to
1..3 vertices of degree < 3) to every graph on n-1 vertices and keeping one graph per isomorphism class (canonical form =
minimum edge set over all vertex permutations). Every connected graph has a non-cut vertex, so nothing is missed.
Walk: start anywhere (start counter 1, others 0); each move goes to a neighbour with the smallest counter and
increments it; T = number of moves until all counters are positive; M = largest counter seen at any time t < T.
Both maxima are over graphs, starts and all tie choices (memoised search over states).
Prints per n: number of graphs, max T (all), max M (all), max T (trees), max T (cubic graphs, '-' if none).
"""
import sys
from itertools import combinations, permutations


def canon(n, edges):
    best = None
    for p in permutations(range(n)):
        e = tuple(sorted((min(p[a], p[b]), max(p[a], p[b])) for a, b in edges))
        if best is None or e < best:
            best = e
    return best


def extend(n, graphs):                      # graphs on n vertices -> canonical graphs on n+1
    out = set()
    for edges in graphs:
        deg = [0] * n
        for a, b in edges:
            deg[a] += 1
            deg[b] += 1
        free = [v for v in range(n) if deg[v] < 3]
        for k in (1, 2, 3):
            for nb in combinations(free, k):
                out.add(canon(n + 1, list(edges) + [(v, n) for v in nb]))
    return out


def walk_maxima(n, edges):
    adj = [[] for _ in range(n)]
    for a, b in edges:
        adj[a].append(b)
        adj[b].append(a)
    memo = {}

    def go(pos, cnt):                       # returns (max remaining moves, max M over continuations)
        key = (pos, cnt)
        if key in memo:
            return memo[key]
        low = min(cnt[v] for v in adj[pos])
        bt, bm = 0, 0
        here = max(cnt)                     # counters at this time t (< T, since not yet covered)
        for v in adj[pos]:
            if cnt[v] != low:
                continue
            c2 = cnt[:v] + (cnt[v] + 1,) + cnt[v + 1:]
            if min(c2) > 0:
                t, m = 1, here
            else:
                t, m = go(v, c2)
                t, m = t + 1, max(m, here)
            bt, bm = max(bt, t), max(bm, m)
        memo[key] = (bt, bm)
        return bt, bm

    T = M = 0
    if n == 1:
        return 0, 0
    for s in range(n):
        t, m = go(s, tuple(1 if v == s else 0 for v in range(n)))
        T, M = max(T, t), max(M, m)
    return T, M


sys.setrecursionlimit(100000)
graphs = {()}
maxn = int(sys.argv[1]) if len(sys.argv) > 1 else 7
for n in range(1, maxn + 1):
    if n > 1:
        graphs = extend(n - 1, graphs)
    T = M = TT = TC = 0
    cubic = False
    for edges in graphs:
        t, m = walk_maxima(n, edges)
        T, M = max(T, t), max(M, m)
        if len(edges) == n - 1:
            TT = max(TT, t)
        if 2 * len(edges) == 3 * n:
            cubic, TC = True, max(TC, t)
    print(n, len(graphs), T, M, TT, TC if cubic else "-", flush=True)
